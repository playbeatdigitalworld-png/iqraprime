#!/usr/bin/env python3
"""Regenerate src/data/poster-manifest.ts from files actually present in public/art."""
import os

ART = "/home/z/my-project/iqraprime-app/public/art"
OUT = "/home/z/my-project/iqraprime-app/src/data/poster-manifest.ts"

files = sorted(
    f for f in os.listdir(ART)
    if f.lower().endswith((".jpg", ".jpeg", ".png", ".webp"))
    and os.path.getsize(os.path.join(ART, f)) > 8000
)

# one entry per id stem; prefer jpg > jpeg > png > webp
PRIO = {".jpg": 0, ".jpeg": 1, ".png": 2, ".webp": 3}
by_stem: dict = {}
for f in files:
    stem, ext = os.path.splitext(f)
    ext = ext.lower()
    if stem not in by_stem or PRIO[ext] < PRIO[by_stem[stem][1]]:
        by_stem[stem] = (f, ext)

lines = [
    "// AUTO-GENERATED by scripts/regen-poster-manifest.py — id → real poster filename in /public/art",
    "export const POSTER_MANIFEST: Record<string, string> = {",
]
for stem in sorted(by_stem):
    f, _ = by_stem[stem]
    lines.append(f'  "{stem}": "{f}",')
lines.append("}")

with open(OUT, "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"manifest regenerated: {len(files)} real posters")
